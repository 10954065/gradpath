import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { OBJECTIVE_TYPES } from '../../src/lib/content/types'
import type { LoadedCourse } from './loadContent'

const CLASSIFICATION_LABEL = { core: 'Core', required: 'Required', special_topic: 'Special topic', elective: 'Elective' } as const

/** Regenerate CURRICULUM_STATUS.md from the content actually present on disk. */
export function writeCurriculumStatus(courses: LoadedCourse[], verifiedResourceUrls?: ReadonlySet<string>): void {
  const today = new Date().toISOString().slice(0, 10)
  const rows: string[] = []
  const details: string[] = []

  for (const c of courses) {
    const lessons = c.modules.flatMap((m) => m.lessons)
    const written = lessons.filter((l) => l.parsed)
    const quizzesReady = c.modules.flatMap((m) =>
      m.lessons.filter((l) => m.questions.filter((q) => q.lesson === l.slug && OBJECTIVE_TYPES.includes(q.type)).length >= 6),
    ).length
    const assessmentsReady = c.modules.filter(
      (m) => m.lessons.length > 0 && m.questions.some((q) => q.type === 'essay' || q.type === 'case_analysis'),
    ).length
    const verified = verifiedResourceUrls ? c.resources.filter((r) => verifiedResourceUrls.has(r.url)).length : null
    const complete =
      written.length === lessons.length && quizzesReady === lessons.length && assessmentsReady === c.modules.length && c.resources.length > 0
    const outstanding: string[] = []
    if (written.length < lessons.length) outstanding.push(`${lessons.length - written.length} lesson(s)`)
    if (quizzesReady < lessons.length) outstanding.push(`${lessons.length - quizzesReady} lesson quiz bank(s)`)
    if (assessmentsReady < c.modules.length) outstanding.push(`${c.modules.length - assessmentsReady} module assessment(s)`)
    if (!c.resources.length) outstanding.push('resources')

    rows.push(
      `| ${c.outline.code} ${c.outline.title} | ${CLASSIFICATION_LABEL[c.outline.classification]} | ${c.outline.creditSlots} | ${c.modules.length} | ${lessons.length} | ${written.length} | ${quizzesReady} | ${assessmentsReady} | ${c.resources.length}${verified === null ? '' : ` (${verified} verified)`} | ${complete ? 'Complete' : outstanding.join(', ')} |`,
    )

    details.push(`### ${c.outline.code} — ${c.outline.title}\n`)
    details.push('| Module | Lessons written | Questions | Flashcards |')
    details.push('|---|---|---|---|')
    for (const m of c.modules) {
      details.push(
        `| ${m.order}. ${m.title} | ${m.lessons.filter((l) => l.parsed).length}/${m.lessons.length} | ${m.questions.length} | ${m.flashcards.length} |`,
      )
    }
    details.push('')
  }

  const doc = `# GradPath — Curriculum Status

_Generated by \`npm run content:build\` on ${today}. Counts reflect files that pass validation; a lesson
is only counted as written when it meets the content specification (no placeholder content)._

All lessons are original **supplementary** study material; all questions are **supplementary practice
questions**. Neither is official University of Ghana material.

| Course | Classification | Credit slots | Modules | Planned lessons | Completed lessons | Completed lesson quizzes | Completed module assessments | Resources | Outstanding |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Programme listing: ${courses.length} courses, ${courses.reduce((sum, c) => sum + c.outline.creditSlots, 0)} credit slots in total. Each student's
own selection (core, required and special-topic courses plus their chosen elective) is recorded in the app under
Settings, Courses.

A lesson quiz is complete when its lesson has at least six objective practice questions; a module
assessment is complete when the module bank also includes an essay or case-analysis question with a
rubric. Each course also receives a generated course-level mock examination drawn from its bank.

## Per-module detail

${details.join('\n')}
`
  writeFileSync(join(process.cwd(), 'CURRICULUM_STATUS.md'), doc)
  console.log('Wrote CURRICULUM_STATUS.md')
}
